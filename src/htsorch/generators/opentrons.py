"""Generate Opentrons Flex protocols (Python API) from a validated spec.

Three protocols are produced: dilution series on the prep plate, media + cell
seeding, and reagent addition at readout. Scientists never edit these files."""
from __future__ import annotations

import json

from ..platemap import build_plate_map
from ..spec import POS_WELL, VEHICLE_WELL, derive, prep_well

API_LEVEL = "2.19"
TIPRACK = "opentrons_flex_96_tiprack_50ul"
HEADER = '''"""GENERATED by hts-orchestrator from spec {sid} (sha256 {sha}). Do not edit by hand."""
from opentrons import protocol_api

metadata = {{"protocolName": "{name}", "author": "hts-orchestrator (generated)", "description": "{desc}"}}
requirements = {{"robotType": "Flex", "apiLevel": "{api}"}}
'''


def _header(spec, name, desc):
    return HEADER.format(sid=spec["experiment"]["id"], sha=spec["_meta"]["sha256"][:12],
                         name=name, desc=desc, api=API_LEVEL)


def _plan_dilution(spec, d):
    points = spec["dilution"]["points"]
    top_vol = spec["prep_plate"]["well_volume_ul"]
    fill, series = [], []
    for i, cid in enumerate(spec["compounds"]["ids"]):
        wells = [prep_well(i, j, points) for j in range(points)]
        fill.append([wells[0], round(top_vol - d["top_master_ul"], 3)])
        fill += [[w, round(d["remaining_ul"], 3)] for w in wells[1:]]
        series.append({"id": cid, "master_well": _master_well(i),
                       "master_ul": round(d["top_master_ul"], 3), "wells": wells})
    fill.append([POS_WELL, round(top_vol - d["pos_master_ul"], 3)])
    fill.append([VEHICLE_WELL, round(top_vol, 3)])
    series.append({"id": "KILL", "master_well": _master_well(len(spec["compounds"]["ids"])),
                   "master_ul": round(d["pos_master_ul"], 3), "wells": [POS_WELL]})
    return {"transfer_ul": round(d["step_ul"], 3), "dmso_fill": fill, "series": series}


def _master_well(index: int) -> str:
    """Master stock plate is a 96-well plate filled column-wise: A1, B1, ... H1, A2 ..."""
    return f"{'ABCDEFGH'[index % 8]}{index // 8 + 1}"


def generate_dilution(spec: dict, d: dict | None = None) -> str:
    d = d or derive(spec)
    plan = _plan_dilution(spec, d)
    return _header(spec, "HTS dilution series", "Build 5-point DMSO dilution series in the iDOT prep plate") + f'''
PLAN = {json.dumps(plan, indent=1)}


def run(protocol: protocol_api.ProtocolContext):
    protocol.load_trash_bin("A3")
    tips = protocol.load_labware("{TIPRACK}", "C1")
    master = protocol.load_labware("nest_96_wellplate_100ul_pcr_full_skirt", "D1", "Master stock plate")
    prep = protocol.load_labware("{spec["assay"]["plate"]["opentrons_load_name"]}", "D2", "iDOT prep plate (stand-in definition)")
    dmso_res = protocol.load_labware("{spec["flex"]["reservoirs"]["dmso"]["load_name"]}", "D3", "DMSO")
    p50 = protocol.load_instrument("flex_1channel_50", "left", tip_racks=[tips])
    dmso = dmso_res["A1"]

    protocol.comment("Load DMSO reservoir with at least {d["reservoir_need_ul"]["dmso"] / 1000 + spec["flex"]["reservoirs"]["dmso"]["dead_volume_ul"] / 1000:.1f} mL")
    protocol.comment("Step 1: distribute DMSO diluent into prep-plate wells")
    p50.pick_up_tip()
    for well, vol in PLAN["dmso_fill"]:
        p50.transfer(vol, dmso, prep[well], new_tip="never")
    p50.drop_tip()

    protocol.comment("Step 2: master stock -> top point, then serial dilution, one tip per compound")
    for s in PLAN["series"]:
        p50.pick_up_tip()
        p50.transfer(s["master_ul"], master[s["master_well"]], prep[s["wells"][0]], mix_after=(3, 10), new_tip="never")
        for src, dst in zip(s["wells"], s["wells"][1:]):
            p50.transfer(PLAN["transfer_ul"], prep[src], prep[dst], mix_after=(3, 10), new_tip="never")
        p50.drop_tip()
'''


def _fill_protocol(spec, d, name, desc, steps, wells=None, post_comments=()):
    """steps: list of (label, reservoir_key, volume_ul, deck_slot, mix_every).

    wells=None  -> 8-channel fills every well of the 384-well plate (two passes, odd/even rows)
    wells=[...] -> 1-channel fills only the listed wells, well by well"""
    plate = spec["assay"]["plate"]["opentrons_load_name"]
    body = _header(spec, name, desc)
    body += f'''
OVERAGE_UL = {spec["flex"]["overage_ul"]}
'''
    if wells is None:
        body += '''

def fill(protocol, pipette, plate, source, volume_ul, per_aspirate, mix_every=None):
    """Fill every well of a 384-well plate with an 8-channel pipette (two passes: odd and even rows)."""
    pipette.pick_up_tip()
    cycle = 0
    for row in (plate.rows()[0], plate.rows()[1]):
        for i in range(0, len(row), per_aspirate):
            targets = row[i:i + per_aspirate]
            if mix_every and cycle % mix_every == 0:
                pipette.mix(5, 40, source)
            pipette.aspirate(volume_ul * len(targets) + OVERAGE_UL, source)
            for t in targets:
                pipette.dispense(volume_ul, t.top(-2))
            pipette.blow_out(source.top())
            cycle += 1
    pipette.drop_tip()
'''
        pip_line = 'p = protocol.load_instrument("flex_8channel_50", "right", tip_racks=[tips])'
    else:
        body += f'''
WELLS = {json.dumps(wells)}


def fill_wells(protocol, pipette, plate, source, wells, volume_ul, per_aspirate, mix_every=None):
    """Fill only the listed wells, one well at a time (1-channel)."""
    pipette.pick_up_tip()
    cycle = 0
    for i in range(0, len(wells), per_aspirate):
        targets = wells[i:i + per_aspirate]
        if mix_every and cycle % mix_every == 0:
            pipette.mix(3, 40, source)
        pipette.aspirate(volume_ul * len(targets) + OVERAGE_UL, source)
        for w in targets:
            pipette.dispense(volume_ul, plate[w].top(-2))
        pipette.blow_out(source.top())
        cycle += 1
    pipette.drop_tip()
'''
        pip_line = 'p = protocol.load_instrument("flex_1channel_50", "left", tip_racks=[tips])'

    body += f'''

def run(protocol: protocol_api.ProtocolContext):
    protocol.load_trash_bin("A3")
    tips = protocol.load_labware("{TIPRACK}", "C1")
    plate = protocol.load_labware("{plate}", "D2", "Assay plate (ULA round-bottom, stand-in definition)")
    {pip_line}
'''
    for label, key, vol, slot, mix, n in steps:
        res = spec["flex"]["reservoirs"][key]
        need = (d["reservoir_need_ul"][key] + res["dead_volume_ul"]) / 1000.0
        body += f'''
    {key} = protocol.load_labware("{res["load_name"]}", "{slot}", "{label}")["A1"]
    protocol.comment("Load {label}: at least {need:.1f} mL in the reservoir")
'''
    for label, key, vol, slot, mix, n in steps:
        if wells is None:
            call = f"fill(protocol, p, plate, {key}, {vol:g}, {n}, mix_every={mix})"
        else:
            call = f"fill_wells(protocol, p, plate, {key}, WELLS, {vol:g}, {n}, mix_every={mix})"
        body += f'''
    protocol.comment("Dispense {label}: {vol:g} uL per well")
    {call}
'''
    for c in post_comments:
        body += f'    protocol.comment("{c}")\n'
    return body


def _well_list(plate_map, keep) -> list[str]:
    return [w["well"] for w in sorted(plate_map, key=lambda w: (w["row"], w["col"])) if keep(w)]


def generate_edge_fill(spec: dict, d: dict | None, plate_map: list) -> str:
    """PBS pre-fill of the perimeter and unused wells. Runs on the empty plate, before the iDOT step."""
    d = d or derive(spec)
    wells = _well_list(plate_map, lambda w: w["type"] == "pbs")
    steps = [("PBS", "pbs", d["pbs_volume_ul"], "D3", None, d["dispenses_per_aspirate"]["pbs"])]
    return _fill_protocol(spec, d, "HTS edge fill", "Fill perimeter and unused wells with PBS to limit evaporation effects",
                          steps, wells=wells)


def generate_seeding(spec: dict, d: dict | None = None, plate_map: list | None = None) -> str:
    d = d or derive(spec)
    a = spec["assay"]
    dp = d["dispenses_per_aspirate"]
    steps = [
        ("Media", "media", a["media_volume_ul"], "D3", None, dp["media"]),
        ("Cell suspension (resuspend gently before loading)", "cells", a["cell_volume_ul"], "D1",
         spec["flex"]["mix_cell_every_cycles"], dp["cells"]),
    ]
    wells = None
    if d["well_by_well"]:
        plate_map = plate_map or build_plate_map(spec, d)
        wells = _well_list(plate_map, lambda w: w["type"] != "pbs")
    return _fill_protocol(spec, d, "HTS seeding", "Add media then cell suspension to the compound-loaded assay plate",
                          steps, wells=wells)


def generate_readout(spec: dict, d: dict | None = None) -> str:
    d = d or derive(spec)
    r = spec["assay"]["reagent"]
    steps = [(r["name"], "reagent", d["reagent_volume_ul"], "D3", None, d["dispenses_per_aspirate"]["reagent"])]
    notes = (
        f"NEXT (orchestrator-controlled, off this deck): shake {r['shake_min']:g} min, "
        f"incubate {r['incubate_min']:g} min, then read luminescence",
        "Spheroids need longer lysis than 2D cultures; do not shorten these times",
    )
    return _fill_protocol(spec, d, "HTS readout reagent", "Add viability reagent to every well before the plate reader",
                          steps, post_comments=notes)
